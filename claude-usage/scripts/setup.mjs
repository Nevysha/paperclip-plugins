#!/usr/bin/env node
// Turns setup.json (your company, project and routines; not committed) into src/setup.generated.ts,
// which the plugin is built from. Without setup.json it uses setup.example.json: no routines, so the
// header still shows usage but the panel lists nothing to pause.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const local = join(root, "setup.json");
const source = existsSync(local) ? local : join(root, "setup.example.json");
const setup = JSON.parse(readFileSync(source, "utf8"));

const fail = (msg) => { console.error(`${source}: ${msg}`); process.exit(1); };
if (typeof setup.companyId !== "string" || typeof setup.projectId !== "string") fail("companyId and projectId must be strings");
if (!Array.isArray(setup.routines)) fail("routines must be a list");
if (setup.routines.length && (!setup.companyId || !setup.projectId)) fail("routines need companyId and projectId");
for (const r of setup.routines) {
  for (const field of ["key", "title", "description", "label", "cron", "assigneeAgentId"]) {
    if (typeof r[field] !== "string" || !r[field]) fail(`every routine needs a non-empty "${field}"`);
  }
  if (typeof r.defaultEnabled !== "boolean") fail(`routine "${r.key}" needs "defaultEnabled": true or false`);
}
if (new Set(setup.routines.map((r) => r.key)).size !== setup.routines.length) fail("routine keys must be unique");

const out = `// Generated by scripts/setup.mjs from ${source === local ? "setup.json" : "setup.example.json"}. Don't edit.
import type { Setup } from "./setup.js";

const setup: Setup = ${JSON.stringify({ timezone: "UTC", ...setup }, null, 2)};
export default setup;
`;
writeFileSync(join(root, "src/setup.generated.ts"), out);
